# Tipos de datos en Python y sus características
# strings, enteros, flotantes, booleanos, listas, tuplas, diccionarios y conjuntos, NoneType , dict , range , set ...

type("Hola Mundo") # str
type(10) # int  
type(3.14) # float
type(True) # bool
type([1, 2, 3]) # list
type((1, 2, 3)) # tuple
type({"clave": "valor"}) # dict
type({1, 2, 3}) # set
type( 1 + 2j) # complex
type( "" ) # str
type("123") # str
type("""Hello, World!""") # str


type(None) # NoneType
